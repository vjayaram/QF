namespace Qf.ModelGen.Tests;

public class GenerationTests
{
    private readonly IReadOnlyList<GeneratedFile> _files = Generator.Generate(ModelFixtures.Load());

    [Fact]
    public void EmitsOneFilePerConcern()
    {
        var paths = _files.Select(f => f.RelativePath).ToList();

        Assert.Equal(
            new[]
            {
                "out/Domain/Enums.g.cs", "out/Domain/ValueObjects.g.cs", "out/Domain/Aggregates.g.cs", "out/Domain/Events.g.cs",
                "out/Infra/EntityConfigurations.g.cs", "out/Api/GraphQLTypes.g.cs", "out/Db/Widgets.g.sql",
            },
            paths);
    }

    [Fact]
    public void Output_IsDeterministic_WithLfEndings()
    {
        var again = Generator.Generate(ModelFixtures.Load());

        Assert.Equal(_files, again);
        Assert.All(_files, f => Assert.DoesNotContain("\r", f.Content, StringComparison.Ordinal));
        Assert.All(_files.Where(f => f.RelativePath.EndsWith(".cs", StringComparison.Ordinal)), f => Assert.StartsWith("// <auto-generated>", f.Content, StringComparison.Ordinal));
    }

    [Fact]
    public void ValueObjects_ValidateAndRedact()
    {
        var code = ModelFixtures.File(_files, "ValueObjects.g.cs");

        Assert.Contains("public static Result<Code> Create(string value)", code, StringComparison.Ordinal);
        Assert.Contains("\"Code.Value.TooLong\"", code, StringComparison.Ordinal);
        Assert.Contains("\"Code.Value.InvalidFormat\"", code, StringComparison.Ordinal);
        Assert.Contains("public static Code Rehydrate(string value)", code, StringComparison.Ordinal);
        Assert.Contains("builder.Append(\"Text = ***\");", code, StringComparison.Ordinal);
        Assert.Contains("builder.Append(\", Hint = \").Append(Hint);", code, StringComparison.Ordinal);
        Assert.Contains("public string? Hint { get; private init; }", code, StringComparison.Ordinal);
    }

    [Fact]
    public void Aggregates_GetStateMachineAndPhiMarkers()
    {
        var code = ModelFixtures.File(_files, "Aggregates.g.cs");

        Assert.Contains("public sealed partial class Widget : AggregateRoot<Guid>", code, StringComparison.Ordinal);
        Assert.Contains("private Result TransitionColorTo(Color target)", code, StringComparison.Ordinal);
        Assert.Contains("[Phi]\n    public Secret Secret { get; private set; } = null!;", code, StringComparison.Ordinal);
        Assert.Contains("public decimal Price { get; private set; }\n", code, StringComparison.Ordinal);
    }

    [Fact]
    public void Enums_StartAtOne_AndListTransitions()
    {
        var code = ModelFixtures.File(_files, "Enums.g.cs");

        Assert.Contains("Red = 1,", code, StringComparison.Ordinal);
        Assert.Contains("(Color.Red, Color.Green),", code, StringComparison.Ordinal);
    }

    [Fact]
    public void EfMapping_UsesConvertersOwnedTypesAndConcurrency()
    {
        var code = ModelFixtures.File(_files, "EntityConfigurations.g.cs");

        Assert.Contains(".HasConversion(v => v.Value, v => Code.Rehydrate(v))", code, StringComparison.Ordinal);
        Assert.Contains("builder.OwnsOne(x => x.Secret, owned =>", code, StringComparison.Ordinal);
        Assert.Contains("builder.Property<byte[]>(\"RowVersion\").IsRowVersion();", code, StringComparison.Ordinal);
        Assert.Contains("builder.HasIndex(x => new { x.TenantId, x.Code }).IsUnique();", code, StringComparison.Ordinal);
        Assert.Contains(".HasPrecision(10, 2)", code, StringComparison.Ordinal);
        Assert.Contains("builder.Property(x => x.Color).HasConversion<string>()", code, StringComparison.Ordinal);
    }

    [Fact]
    public void GraphQL_GuardsPhiFieldsOnly()
    {
        var code = ModelFixtures.File(_files, "GraphQLTypes.g.cs");

        Assert.Contains("descriptor.Field(x => x.Secret).Authorize(GraphQLPolicies.PhiRead).Use<PhiAccessAuditMiddleware>();", code, StringComparison.Ordinal);
        Assert.Contains("descriptor.Field(x => x.Color);", code, StringComparison.Ordinal);
        Assert.Contains("descriptor.BindFieldsExplicitly();", code, StringComparison.Ordinal);
        Assert.Contains(".AddType<SecretType>()", code, StringComparison.Ordinal);
    }

    [Fact]
    public void Sql_MatchesEfMapping()
    {
        var sql = ModelFixtures.File(_files, "Widgets.g.sql");

        Assert.Contains("[Code] NVARCHAR(10) NOT NULL", sql, StringComparison.Ordinal);
        Assert.Contains("[Secret_Text] NVARCHAR(20) NOT NULL", sql, StringComparison.Ordinal);
        Assert.Contains("[Secret_Hint] NVARCHAR(20) NULL", sql, StringComparison.Ordinal);
        Assert.Contains("[Price] DECIMAL(10, 2) NOT NULL", sql, StringComparison.Ordinal);
        Assert.Contains("CHECK ([Color] IN (N'Red', N'Green'))", sql, StringComparison.Ordinal);
        Assert.Contains("[RowVersion] ROWVERSION NOT NULL", sql, StringComparison.Ordinal);
        Assert.Contains("[UX_Widgets_TenantId_Code]", sql, StringComparison.Ordinal);
    }
}
