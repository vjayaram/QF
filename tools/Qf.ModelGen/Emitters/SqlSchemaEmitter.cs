using System.Text;

namespace Qf.ModelGen.Emitters;

/// <summary>
/// Emits Azure SQL DDL into a SQL Database Project (Microsoft.Build.Sql). The pipeline builds a DACPAC
/// and deploys it with sqlpackage, so the schema is declarative and diffed by the tooling.
/// Because EF mappings and DDL come from the same model, they cannot disagree.
/// Enum columns get CHECK constraints listing the allowed values.
/// </summary>
internal static class SqlSchemaEmitter
{
    public static IEnumerable<GeneratedFile> Emit(DomainModel model, ModelIndex index)
    {
        foreach (var agg in model.Aggregates)
        {
            yield return new(DomainEmitter.Combine(model.Outputs.Database, $"{agg.Table}.g.sql"), EmitAggregateTable(model, agg, index));
            foreach (var c in agg.Collections)
            {
                yield return new(DomainEmitter.Combine(model.Outputs.Database, $"{c.Table}.g.sql"), EmitCollectionTable(model, agg, c, index));
            }
        }
    }

    private static string Prelude(DomainModel model) =>
        $"-- <auto-generated>\n--   Generated by Qf.ModelGen from {model.SourcePath}. Do not edit.\n-- </auto-generated>\n";

    private static string EmitAggregateTable(DomainModel model, AggregateModel agg, ModelIndex index)
    {
        var columns = new List<string>
        {
            "[Id] UNIQUEIDENTIFIER NOT NULL",
            "[TenantId] UNIQUEIDENTIFIER NOT NULL",
        };
        var checks = new List<string>();

        foreach (var f in agg.Fields)
        {
            var t = index.Resolve(f.Type);
            if (t.Kind == TypeKind.ValueObject)
            {
                var vo = index.ValueObject(f.Type);
                foreach (var sub in vo.Fields)
                {
                    var column = vo.Fields.Count == 1 ? f.Name : $"{f.Name}_{sub.Name}";
                    columns.Add(Column(column, sub, index, f.Required && sub.Required));
                    AddCheck(checks, agg.Table, column, sub, index);
                }

                continue;
            }

            columns.Add(Column(f.Name, f, index, f.Required));
            AddCheck(checks, agg.Table, f.Name, f, index);
        }

        columns.Add("[RowVersion] ROWVERSION NOT NULL");
        columns.Add($"CONSTRAINT [PK_{agg.Table}] PRIMARY KEY CLUSTERED ([Id])");
        columns.AddRange(checks);

        var sb = new StringBuilder(Prelude(model));
        sb.Append($"CREATE TABLE [dbo].[{agg.Table}]\n(\n");
        sb.Append(string.Join(",\n", columns.Select(c => "    " + c)));
        sb.Append("\n);\nGO\n\n");
        sb.Append($"CREATE NONCLUSTERED INDEX [IX_{agg.Table}_TenantId] ON [dbo].[{agg.Table}] ([TenantId]);\nGO\n");

        foreach (var f in agg.Fields.Where(f => f.Unique))
        {
            sb.Append($"\nCREATE UNIQUE NONCLUSTERED INDEX [UX_{agg.Table}_TenantId_{f.Name}] ON [dbo].[{agg.Table}] ([TenantId], [{f.Name}]);\nGO\n");
        }

        foreach (var ix in agg.Indexes)
        {
            var name = string.Join("_", ix);
            var cols = string.Join(", ", ix.Select(c => $"[{c}]"));
            sb.Append($"\nCREATE NONCLUSTERED INDEX [IX_{agg.Table}_TenantId_{name}] ON [dbo].[{agg.Table}] ([TenantId], {cols});\nGO\n");
        }

        return sb.ToString();
    }

    private static string EmitCollectionTable(DomainModel model, AggregateModel agg, CollectionModel c, ModelIndex index)
    {
        var vo = index.ValueObject(c.Type);
        var columns = new List<string>
        {
            "[Id] INT IDENTITY(1, 1) NOT NULL",
            $"[{agg.Name}Id] UNIQUEIDENTIFIER NOT NULL",
        };
        var checks = new List<string>();
        foreach (var sub in vo.Fields)
        {
            columns.Add(Column(sub.Name, sub, index, sub.Required));
            AddCheck(checks, c.Table, sub.Name, sub, index);
        }

        columns.Add($"CONSTRAINT [PK_{c.Table}] PRIMARY KEY CLUSTERED ([Id])");
        columns.Add($"CONSTRAINT [FK_{c.Table}_{agg.Table}] FOREIGN KEY ([{agg.Name}Id]) REFERENCES [dbo].[{agg.Table}] ([Id]) ON DELETE CASCADE");
        columns.AddRange(checks);

        var sb = new StringBuilder(Prelude(model));
        sb.Append($"CREATE TABLE [dbo].[{c.Table}]\n(\n");
        sb.Append(string.Join(",\n", columns.Select(col => "    " + col)));
        sb.Append("\n);\nGO\n\n");
        sb.Append($"CREATE NONCLUSTERED INDEX [IX_{c.Table}_{agg.Name}Id] ON [dbo].[{c.Table}] ([{agg.Name}Id]);\nGO\n");
        if (c.UniqueAcross.Count > 0)
        {
            var cols = string.Join(", ", c.UniqueAcross.Select(u => $"[{u}]"));
            sb.Append($"\nCREATE UNIQUE NONCLUSTERED INDEX [UX_{c.Table}_{string.Join("_", c.UniqueAcross)}] ON [dbo].[{c.Table}] ({cols});\nGO\n");
        }

        return sb.ToString();
    }

    private static string Column(string name, FieldModel f, ModelIndex index, bool required) =>
        $"[{name}] {SqlType(f, index)} {(required ? "NOT NULL" : "NULL")}";

    private static void AddCheck(List<string> checks, string table, string column, FieldModel f, ModelIndex index)
    {
        if (index.Resolve(f.Type).Kind != TypeKind.Enum)
        {
            return;
        }

        var values = string.Join(", ", index.Enum(f.Type).Values.Select(v => $"N'{v}'"));
        checks.Add($"CONSTRAINT [CK_{table}_{column}] CHECK ([{column}] IN ({values}))");
    }

    private static string SqlType(FieldModel f, ModelIndex index)
    {
        var t = index.Resolve(f.Type);
        if (t.Kind == TypeKind.Enum)
        {
            return "NVARCHAR(32)";
        }

        return f.Type switch
        {
            "string" => $"NVARCHAR({f.MaxLength})",
            "int" => "INT",
            "long" => "BIGINT",
            "bool" => "BIT",
            "decimal" => $"DECIMAL({f.Precision ?? 18}, {f.Scale ?? 2})",
            "Guid" => "UNIQUEIDENTIFIER",
            "DateOnly" => "DATE",
            "TimeOnly" => "TIME(7)",
            "DateTimeOffset" => "DATETIMEOFFSET(7)",
            _ => throw new InvalidOperationException($"No SQL type mapping for '{f.Type}'."),
        };
    }
}
