namespace Qf.ModelGen.Emitters;

internal static class Header
{
    public static CodeWriter Start(DomainModel model, string ns, params string[] usings)
    {
        var w = new CodeWriter();
        w.Line("// <auto-generated>")
         .Line($"//   Generated by Qf.ModelGen from {model.SourcePath}.")
         .Line("//   Do not edit. Change the model and re-run the generator; CI fails on drift.")
         .Line("// </auto-generated>")
         .Line("#nullable enable")
         .Line();
        foreach (var u in usings.Distinct(StringComparer.Ordinal).OrderBy(u => u.StartsWith("System", StringComparison.Ordinal) ? 0 : 1).ThenBy(u => u, StringComparer.Ordinal))
        {
            w.Line($"using {u};");
        }

        if (usings.Length > 0)
        {
            w.Line();
        }

        w.Line($"namespace {ns};");
        return w;
    }
}
